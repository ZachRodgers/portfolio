const { spawn } = require('child_process');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/home/Zach/.cache/ms-playwright-go/1.50.1/package');
const server = spawn('python3', ['-m', 'http.server', '8785', '-d', 'public']);
process.on('exit', () => server.kill());
(async () => {
  await new Promise(resolve => setTimeout(resolve, 600));
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  page.setDefaultTimeout(8000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:8785/');
  await page.evaluate(() => new Promise(resolve => { const frame = document.createElement('iframe'); frame.onload = resolve; frame.src = '/assets/ux_ui/content/portfolio/parallel/superadmin/index.html'; document.body.appendChild(frame); }));
  const preview = page.frameLocator('iframe');
  await preview.locator('#root').waitFor({ state: 'attached' });
  if (await preview.locator('.superadmin-header').count()) throw Error('Superadmin started before entering view');
  await page.evaluate(() => document.querySelector('iframe').contentWindow.postMessage({type:'mc-demo',visible:true}, location.origin));
  await preview.locator('.cameras-preview-skeleton').waitFor();
  await preview.locator('.superadmin-header').waitFor();
  await preview.getByRole('button', { name: 'Shutdown' }).first().waitFor();
  if (await preview.locator('.cameras-preview-skeleton').count()) throw Error('Camera skeleton did not finish loading');
  await page.goto('http://127.0.0.1:8785/assets/ux_ui/content/portfolio/parallel/superadmin/index.html');
  await page.getByRole('button', { name: 'Shutdown' }).first().waitFor();
  if (await page.getByText('Welcome to Parallel!').count()) throw Error('Tutorial appeared in Superadmin');
  await page.getByRole('button', { name: 'Shutdown' }).first().click();
  await page.getByText('Offline', { exact: true }).first().waitFor();
  await page.getByRole('button', { name: 'Add camera' }).click();
  await page.getByRole('button', { name: 'Add Camera', exact: true }).click();
  await page.getByText('Recently Added', { exact: false }).first().waitFor();
  await page.locator('[data-nav-path$="/superadmin/alpr-log"]').click();
  await page.getByRole('button', { name: '+ Manual Entry' }).click();
  await page.getByPlaceholder('ABC123').fill('DINO777');
  await page.getByRole('button', { name: 'Add Entry' }).click();
  await page.getByText('DINO777', { exact: true }).first().waitFor();
  await page.locator('[data-nav-path$="/superadmin/sessions"]').click();
  await page.getByText('BRONTO1', { exact: true }).first().waitFor();
  const plateFits = await page.getByText('BRONTO1', { exact: true }).first().evaluate(element => element.scrollWidth <= element.clientWidth);
  if (!plateFits) throw Error('Plate text exceeds its badge');
  await page.locator('[data-nav-path$="/superadmin/disputes"]').click();
  await page.getByText('RAPTORX', { exact: true }).first().click();
  await page.getByRole('button', { name: 'Accept', exact: true }).click();
  await page.getByText('RAPTORX', { exact: true }).waitFor({ state: 'detached' });
  await page.getByRole('button', { name: 'Docs', exact: true }).click();
  await page.getByRole('button', { name: 'New Doc' }).click();
  await page.getByPlaceholder('Parallel Pay workflows').fill('Demo local note');
  await page.getByPlaceholder('Markdown or rich text instructions...').fill('Example support note');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByText('Demo local note', { exact: true }).first().waitFor();
  await page.getByRole('button', { name: 'Agents', exact: true }).click();
  await page.getByRole('button', { name: 'New Agent' }).click();
  await page.getByPlaceholder('unique-agent-key').fill('demo_helper');
  await page.getByPlaceholder('Agent Name').fill('Demo Helper');
  await page.getByPlaceholder("Describe the agent's goals and required output format...").fill('Help review parking data.');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByText('Demo Helper', { exact: true }).first().waitFor();
  await page.getByRole('button', { name: 'All Lots', exact: true }).click();
  await page.getByText('Harbour Centre', { exact: true }).first().waitFor();
  if (errors.length) throw Error(errors.join('\n'));
  console.log('Cameras, ALPR, sessions, disputes, docs, agents and lots passed');
  await browser.close();
  server.kill();
})().catch(error => { console.error(error); server.kill(); process.exitCode = 1; });
